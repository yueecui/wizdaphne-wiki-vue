/**
 * Wiki data transport layer.
 *
 * Data lives on the wiki (``Data:`` namespace) and is served by the Scribunto
 * modules ``Api/GetV2Character`` / ``Api/GetV2Job`` / ``Api/GetV2Skill`` /
 * ``Api/GetV2Enum`` / ``Api/GetV2EffectKind`` / ``Api/GetV2Version``.
 *
 * ``Api/GetV2EffectKind`` is the hand-maintained effect kind name table: it lives
 * only on the wiki (DEV reads ``public/mock/EffectKindResponse.json``) and is
 * never written by the build, so names can be corrected there directly.
 *
 * In dev the same payloads are read from ``public/mock/*Response.json``
 * (generated by ``local_scripts/clean/build_mock.py``), so the
 * frontend works offline and without a wiki account.
 */

import { IS_DEV } from '../util';

export type ModuleName = 'Character' | 'Job' | 'Skill' | 'Enum' | 'EffectKind';

/** 效果种类的一项：根节点 key 就是 kind 编号 */
export interface EffectKind {
    /** 效果种类名 */
    name?: string;
    /** param_1..N 的名称，按位置；``null`` / 缺省 = 沿用数据里的「参数N」 */
    params?: Array<string | null>;
}

/** ``Api/GetV2EffectKind`` 的单条 payload：``{ "<kind>": {...} }`` */
export type EffectKindMap = Record<string, EffectKind>;

/** ``Api/Version`` carries nothing but the version the cache is compared against. */
export interface VersionPayload {
    version: number;
}

export interface ModulePayload<T = unknown> {
    items: T[];
    count: number;
    /**
     * 数据页顶层的补充数据（长键，不压缩）。目前只有 ``Api/GetV2Character`` 用它
     * 携带 ``config/Data_CharacterExtra.tabx.xlsx`` 里的卡池组 / 上线日期 / 声优，
     * 避免混进 items 里。
     */
    extra?: unknown;
    /** 角色个体出现几率（每条带角色 id），同样不进 items */
    rates?: unknown;
}

/** 单次请求的条目上限（与 wiki 端 ``Api/GetV2Xxx`` 的 ``limit`` 参数一致） */
export const PAGE_LIMIT = 10000;
/** 分页安全上限，避免 ``count`` 异常时死循环 */
const MAX_PAGES = 50;

const mockUrl = (name: string) => `${import.meta.env.BASE_URL}mock/${name}Response.json`;
/**
 * 线上与 wiki 同源（COS 绑在 wiki 域名下），所以走相对地址，
 * 和 ``editPage`` / ``getMapConfig`` 一致；跨域请求会被 Cloudflare 挑战拦下。
 * DEV 里 ``/api`` 由 ``vite.config.ts`` 的 proxy 转发。
 */
const luaUrl = (module: string) =>
    `/api.php?action=lua&module=${module}&format=json&utf8=1`;
const apiUrl = (name: ModuleName) => luaUrl(`Api/GetV2${name}`);
const pageUrl = (name: ModuleName, page: number, limit: number) =>
    `${apiUrl(name)}&page=${page}&limit=${limit}`;

async function getJson<T>(url: string): Promise<T> {
    // 数据页会被原地覆盖，不能吃 HTTP 缓存，否则版本变化后仍可能拿到旧内容
    const response = await fetch(url, { cache: 'no-store' });
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);

    const text = await response.text();
    try {
        return JSON.parse(text) as T;
    } catch {
        // 常见于 lua 模块不存在 / 被 Cloudflare 挑战（返回 HTML）
        throw new Error(`${url}: 返回的不是 JSON（模块不存在或被拦截）`);
    }
}

/** ``{data: ...}`` / raw payload wrappers are both accepted */
const unwrap = (data: unknown): unknown => {
    if (data && typeof data === 'object' && 'data' in data) {
        return (data as { data: unknown }).data;
    }
    return data;
};

export async function fetchDataVersion(): Promise<VersionPayload | null> {
    try {
        const data = await getJson<unknown>(
            IS_DEV ? mockUrl('Version') : luaUrl('Api/GetV2Version'),
        );
        const payload = unwrap(data) as Record<string, unknown> | undefined;
        const version = Number(payload?.version ?? 0);
        if (!Number.isFinite(version) || version <= 0) return null;
        return { version };
    } catch {
        // 接口缺失 / 离线：由调用方退回 IndexedDB 缓存
        return null;
    }
}

/**
 * 效果种类名表：模块还没在 wiki 上建好、或离线时都返回 ``null``，不影响主流程。
 * 单条 payload 直接就是 ``{ kind: { name, params } }``。
 */
export async function fetchEffectKind(): Promise<EffectKindMap | null> {
    try {
        const data = unwrap(
            await getJson<unknown>(IS_DEV ? mockUrl('EffectKind') : apiUrl('EffectKind')),
        );

        // 兼容：{items:[{...}]} / [{...}] / {items:{...}} / {...}
        let map: unknown = data;
        if (Array.isArray(map)) {
            map = map[0];
        } else if (map && typeof map === 'object') {
            const { items, ...rest } = map as Record<string, unknown>;
            if (Array.isArray(items)) map = items[0];
            else if (items && typeof items === 'object') map = items;
            else map = rest;
        }

        return map && typeof map === 'object' && !Array.isArray(map)
            ? (map as EffectKindMap)
            : null;
    } catch {
        return null;
    }
}

/** 取一页；DEV 下 mock 就是完整快照，``page`` / ``limit`` 不起作用 */
export async function fetchModuleItems<T = unknown>(
    name: ModuleName,
    page = 1,
    limit = PAGE_LIMIT,
): Promise<ModulePayload<T>> {
    const data = unwrap(await getJson<unknown>(IS_DEV ? mockUrl(name) : pageUrl(name, page, limit)));

    const payload = data as { items?: T[]; count?: number; extra?: unknown; rates?: unknown } | T[] | null;
    const items = Array.isArray(payload) ? payload : payload?.items;

    if (!Array.isArray(items)) {
        throw new Error(`Api/GetV2${name}: unexpected payload`);
    }

    return {
        items,
        count: payload && !Array.isArray(payload) ? (payload.count ?? items.length) : items.length,
        extra: payload && !Array.isArray(payload) ? payload.extra : undefined,
        rates: payload && !Array.isArray(payload) ? payload.rates : undefined,
    };
}

/**
 * 分页补齐整类数据：先用 ``page=1`` 拿 ``count``，再按 ``PAGE_LIMIT`` 逐页拉到够数。
 * 数据集通常一两页就取完；某一页为空 / 数量不再增长时提前结束。
 */
export async function fetchAllModuleItems<T = unknown>(name: ModuleName): Promise<ModulePayload<T>> {
    const first = await fetchModuleItems<T>(name, 1, PAGE_LIMIT);
    const total = first.count || first.items.length;
    const all = [...first.items];

    for (let page = 2; page <= MAX_PAGES && all.length < total; page++) {
        const before = all.length;
        const next = await fetchModuleItems<T>(name, page, PAGE_LIMIT);
        if (next.items.length === 0) break;
        all.push(...next.items);
        if (all.length === before) break;
    }

    return { items: all, count: total, extra: first.extra, rates: first.rates };
}
