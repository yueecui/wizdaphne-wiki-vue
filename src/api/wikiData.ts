/**
 * Wiki data transport layer.
 *
 * Data lives on the wiki (``Data:`` namespace) and is served by the Scribunto
 * modules ``Api/GetV2Character`` / ``Api/GetV2Skill`` / ``Api/GetV2Equipment`` /
 * ``Api/GetV2Item`` / ``Api/GetV2Shop`` / ``Api/GetV2Enemy`` / ``Api/GetV2Enum`` /
 * ``Api/GetV2Extra`` / ``Api/Version``.
 *
 * 线上接口**一次返回全量**（没有 ``page`` / ``limit`` / ``count``）。数据量小的类
 * 合并到了大一类的顶层，少开模块：
 *   * ``Api/GetV2Character`` -> ``{items, jobs, rates}``（``jobs`` 是原 ``Api/GetV2Job`` 的条目）
 *   * ``Api/GetV2Item``      -> ``{items, relics}``（``relics`` 是原 ``Api/GetV2Relic`` 的条目）
 *   * ``Api/GetV2Equipment`` -> ``{items}``
 *   * ``Api/GetV2Enum``      -> ``{enum}``（字典）
 *
 * **人工维护（非解包）的数据全部集中在 ``Api/GetV2Extra``**：效果种类名、装备类型基准值、
 * 装备特典分类/获取途径、遗物推荐类别/掉落怪物、角色卡池与声优。它有自己的版本号
 * （``Api/Version`` 的 ``extra`` 字段），改了只需要重拉这一个模块。
 *
 * In dev the same payloads are read from ``public/mock/*Response.json``
 * (generated by ``local_scripts/clean/build_mock.py``), so the
 * frontend works offline and without a wiki account.
 */

import { IS_DEV } from '../util';

export type ModuleName =
    | 'Character'
    | 'Skill'
    | 'Equipment'
    | 'Item'
    | 'Shop'
    | 'Enemy'
    | 'Map'
    | 'EnemyPool'
    | 'Enum'
    | 'Extra';

/** 效果种类的一项：根节点 key 就是 kind 编号 */
export interface EffectKind {
    /** 效果种类名 */
    name?: string;
    /** param_1..N 的名称，按位置；``null`` / 缺省 = 沿用数据里的「参数N」 */
    params?: Array<string | null>;
}

/** ``Api/GetV2Enum`` 的 `kinds`：``{ "<kind>": { name, params } }`` */
export type EffectKindMap = Record<string, EffectKind>;

/**
 * ``Api/Version``：``version`` 是解包数据的版本（整库缓存按它失效），
 * ``extra`` 是人工维护数据（``Api/GetV2Extra``）的版本，单独比较、单独重拉。
 */
export interface VersionPayload {
    version: number;
    /** 人工表版本；接口没给时为 0（此时只在缓存缺 extra 时补拉） */
    extra: number;
}

/** ``Api/GetV2Extra``：人工维护（非解包）的数据，一块一个顶层字段 */
export interface ExtraPayload {
    /** 效果种类名 + 参数名：``{ "<kind>": { name, params } }`` */
    effectKinds: EffectKindMap | null;
    /** 装备类型基准数值：``{ "短剑": { i: 1, c: 2, spe: 4, ... } }`` */
    equipmentBaseStat: Record<string, unknown> | null;
    /** 遗物掉落怪物 / 推荐类别：``[{ id, monster_id, c }]``（``id`` = 物品图鉴编号） */
    relicExtra: unknown[] | null;
    /** 装备特典分类 / 获取途径：``[{ id, soucate, sou }]`` */
    equipmentExtra: unknown[] | null;
    /** 遗物推荐类别可选项与顺序 */
    relicCategory: string[] | null;
    /** 角色补充：``[{ id, index, group, release_date, character_voice }]`` */
    characterExtra: unknown[] | null;
}

export interface ModulePayload<T = unknown> {
    items: T[];
    /** 条目数（= `items.length`，接口不再返回 `count`） */
    count: number;
    /**
     * @deprecated 角色补充已搬到 ``Api/GetV2Extra.characterExtra``，
     * 这里只留作旧接口的兜底。
     */
    extra?: unknown;
    /** 角色个体出现几率（每条带角色 id），同样不进 items */
    rates?: unknown;
    /**
     * @deprecated 装备基准值已搬到 ``Api/GetV2Extra.equipmentBaseStat``，这里只留作兜底。
     */
    baseStat?: unknown;
    /**
     * ``Api/GetV2Map`` 顶层：地图分类（层是 `map`）。线上在 ``map_meta.maps``，
     * mock 在顶层 ``maps``；与 ``jobs`` 一样不进 items，避免每层重复分类信息。
     */
    maps?: unknown;
    /** ``Api/GetV2Character`` 顶层：职业列表（原 ``Api/GetV2Job`` 的 items） */
    jobs?: unknown;
    /** ``Api/GetV2Item`` 顶层：遗物列表（原 ``Api/GetV2Relic`` 的 items） */
    relics?: unknown;
    /** ``Api/GetV2Enemy`` 顶层：敌群列表（线上与敌人同一个模块） */
    enemyPool?: unknown;
    /**
     * @deprecated 已搬到 ``Api/GetV2Extra.relicExtra``（``[{ id, monster_id, c }]``），
     * 这里只留作旧接口的兜底。
     */
    relicsExtra?: unknown;
    /** @deprecated 已搬到 ``Api/GetV2Extra.relicCategory`` */
    relicsCategories?: unknown;
}

/** 把 ``jobs`` / ``relics`` 这类顶层命名数组统一成数组（缺省为空） */
export const asArray = <T = unknown>(value: unknown): T[] => (Array.isArray(value) ? (value as T[]) : []);

const mockUrl = (name: string) => `${import.meta.env.BASE_URL}mock/${name}Response.json`;
/**
 * 线上与 wiki 同源（COS 绑在 wiki 域名下），所以走相对地址，
 * 和 ``editPage`` / ``getMapConfig`` 一致；跨域请求会被 Cloudflare 挑战拦下。
 * DEV 里 ``/api`` 由 ``vite.config.ts`` 的 proxy 转发。
 */
const luaUrl = (module: string) => `/api.php?action=lua&module=${module}&format=json&utf8=1`;
const apiUrl = (name: ModuleName) => luaUrl(`Api/GetV2${name}`);

async function getJson<T>(url: string): Promise<T> {
    // 数据页会被原地覆盖，不能吃 HTTP 缓存，否则版本变化后仍可能拿到旧内容
    const response = await fetch(url, { cache: 'no-store' });
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);

    const text = await response.text();
    try {
        return JSON.parse(text) as T;
    } catch {
        // 常见于 lua 模块不存在 / 被 Cloudflare 挑战（返回 HTML）
        throw new Error(`${url}: 返回的不是 JSON（模块不存在或被拦截）`);
    }
}

/** ``{data: ...}`` / raw payload wrappers are both accepted */
const unwrap = (data: unknown): unknown => {
    if (data && typeof data === 'object' && 'data' in data) {
        return (data as { data: unknown }).data;
    }
    return data;
};

export async function fetchDataVersion(): Promise<VersionPayload | null> {
    try {
        const data = await getJson<unknown>(IS_DEV ? mockUrl('Version') : luaUrl('Api/Version'));
        const payload = unwrap(data) as Record<string, unknown> | undefined;
        const version = Number(payload?.version ?? 0);
        if (!Number.isFinite(version) || version <= 0) return null;
        const extra = Number(payload?.extra ?? 0);
        return { version, extra: Number.isFinite(extra) && extra > 0 ? extra : 0 };
    } catch {
        // 接口缺失 / 离线：由调用方退回 IndexedDB 缓存
        return null;
    }
}

/**
 * ``Api/GetV2Enum`` -> ``{enum, kinds}``：``enum`` 是各分组字典（含 effect_kind 结构）。
 * ``kinds`` 已搬到 ``Api/GetV2Extra.effectKinds``，这里只留作旧接口的兜底。
 */
export async function fetchEnums(): Promise<{ enums: unknown; kinds: EffectKindMap | null }> {
    const data = unwrap(await getJson<unknown>(IS_DEV ? mockUrl('Enum') : apiUrl('Enum')));
    const payload = (Array.isArray(data) ? { items: data } : data) as {
        enum?: unknown;
        kinds?: unknown;
        items?: unknown;
    } | null;

    const items = payload?.items;
    // 兼容旧形状：``{items: [enums]}`` / 裸字典
    const enums = payload?.enum ?? (Array.isArray(items) ? items[0] : items) ?? payload;
    const kinds = payload?.kinds;

    return {
        enums,
        kinds: kinds && typeof kinds === 'object' && !Array.isArray(kinds) ? (kinds as EffectKindMap) : null,
    };
}

/**
 * ``Api/GetV2Extra``：人工维护的数据（效果种类名 / 装备基准值 / 装备特典 / 遗物类别 /
 * 角色补充）。它有独立的版本号，改动后只重拉这一个模块。
 *
 * 形状不对的块一律当作缺失（``null``），由调用方决定兜底或留空。
 */
export async function fetchExtra(): Promise<ExtraPayload> {
    const data = unwrap(await getJson<unknown>(IS_DEV ? mockUrl('Extra') : apiUrl('Extra')));
    const payload = (data && typeof data === 'object' && !Array.isArray(data) ? data : {}) as Record<string, unknown>;

    const asList = <T>(value: unknown): T[] | null => (Array.isArray(value) ? (value as T[]) : null);
    const asDict = (value: unknown): Record<string, unknown> | null =>
        value && typeof value === 'object' && !Array.isArray(value) ? (value as Record<string, unknown>) : null;

    return {
        effectKinds: asDict(payload.effectKinds) as EffectKindMap | null,
        equipmentBaseStat: asDict(payload.equipmentBaseStat),
        relicExtra: asList(payload.relicExtra),
        equipmentExtra: asList(payload.equipmentExtra),
        relicCategory: asList<string>(payload.relicCategory),
        characterExtra: asList(payload.characterExtra),
    };
}

/** 线上模块的条目键（未列出的模块仍用 `items`） */
const ITEMS_KEY: Partial<Record<ModuleName, string>> = {
    Map: 'map',
    Enemy: 'enemy',
    EnemyPool: 'enemy_pool',
};

/**
 * 拉取整类数据。线上模块一次返回全量（没有分页参数），DEV 读 mock 快照。
 * 条目既可能在 `items`，也可能在模块名单数键上（如 `map`）。
 */
export async function fetchModule<T = unknown>(name: ModuleName): Promise<ModulePayload<T>> {
    const data = unwrap(await getJson<unknown>(IS_DEV ? mockUrl(name) : apiUrl(name)));

    const payload = (Array.isArray(data) ? { items: data } : data) as Record<string, unknown> | null;
    // 线上模块把条目数组放在模块名单数键上（`GetV2Map` → `map`），mock 快照仍用 `items`
    const rawItems = payload?.items ?? (payload && ITEMS_KEY[name] ? payload[ITEMS_KEY[name]!] : undefined);

    // 单条目页（Data:Enum.json）的 items 是整表对象，包成单元素数组方便调用方统一处理
    const items = Array.isArray(rawItems)
        ? (rawItems as T[])
        : rawItems && typeof rawItems === 'object'
          ? [rawItems as T]
          : null;

    if (!items) {
        throw new Error(`Api/GetV2${name}: unexpected payload`);
    }

    return {
        items,
        count: items.length,
        extra: payload?.extra,
        rates: payload?.rates,
        baseStat: payload?.baseStat,
        jobs: payload?.jobs,
        relics: payload?.relics,
        enemyPool: payload?.enemy_pool,
        relicsExtra: payload?.relics_extra,
        relicsCategories: payload?.relics_ccate,
        // 线上 `GetV2Map` 把分类放在 `map_meta.maps`，mock 仍是顶层 `maps`
        maps: payload?.maps ?? (payload?.map_meta as { maps?: unknown } | undefined)?.maps,
    };
}
