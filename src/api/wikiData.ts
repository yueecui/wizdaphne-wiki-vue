/**
 * Wiki data transport layer.
 *
 * Data lives on the wiki (``Data:`` namespace) and is served by the Scribunto
 * modules ``Api/GetV2Character`` / ``Api/GetV2Skill`` / ``Api/GetV2Equipment`` /
 * ``Api/GetV2Item`` / ``Api/GetV2Shop`` / ``Api/GetV2Enum`` / ``Api/GetV2Version``.
 *
 * 线上接口**一次返回全量**（没有 ``page`` / ``limit`` / ``count``）。数据量小的类
 * 合并到了大一类的顶层，少开模块：
 *   * ``Api/GetV2Character`` -> ``{items, jobs, extra, rates}``
 *     （``jobs`` 是原 ``Api/GetV2Job`` 的条目，``extra`` / ``rates`` 是角色补充数据）
 *   * ``Api/GetV2Item``      -> ``{items, relics}``
 *     （``relics`` 是原 ``Api/GetV2Relic`` 的条目）
 *   * ``Api/GetV2Equipment`` -> ``{items, baseStat}``
 *   * ``Api/GetV2Enum``      -> ``{enum, kinds}``
 *     （``kinds`` 是原 ``Api/GetV2EffectKind``，Wiki 上手工维护，可缺失）
 *
 * In dev the same payloads are read from ``public/mock/*Response.json``
 * (generated by ``local_scripts/clean/build_mock.py``), so the
 * frontend works offline and without a wiki account.
 */

import { IS_DEV } from '../util';

export type ModuleName = 'Character' | 'Skill' | 'Equipment' | 'Item' | 'Shop' | 'Enum';

/** 效果种类的一项：根节点 key 就是 kind 编号 */
export interface EffectKind {
    /** 效果种类名 */
    name?: string;
    /** param_1..N 的名称，按位置；``null`` / 缺省 = 沿用数据里的「参数N」 */
    params?: Array<string | null>;
}

/** ``Api/GetV2Enum`` 的 `kinds`：``{ "<kind>": { name, params } }`` */
export type EffectKindMap = Record<string, EffectKind>;

/** ``Api/Version`` carries nothing but the version the cache is compared against. */
export interface VersionPayload {
    version: number;
}

export interface ModulePayload<T = unknown> {
    items: T[];
    /** 条目数（= `items.length`，接口不再返回 `count`） */
    count: number;
    /**
     * 数据页顶层的补充数据（长键，不压缩）。只有 ``Api/GetV2Character`` 用它
     * 携带 ``config/Data_CharacterExtra.tabx.xlsx`` 里的卡池组 / 上线日期 / 声优，
     * 避免混进 items 里。
     */
    extra?: unknown;
    /** 角色个体出现几率（每条带角色 id），同样不进 items */
    rates?: unknown;
    /**
     * 装备的类型基准数值（``{ "短剑": { i: 1, c: 2, spe: 4, ... } }``），
     * 在 ``Api/GetV2Equipment`` 顶层；列表用它决定「高于 / 低于基准」的红绿配色。
     */
    baseStat?: unknown;
    /** ``Api/GetV2Character`` 顶层：职业列表（原 ``Api/GetV2Job`` 的 items） */
    jobs?: unknown;
    /** ``Api/GetV2Item`` 顶层：遗物列表（原 ``Api/GetV2Relic`` 的 items） */
    relics?: unknown;
}

/** 把 ``jobs`` / ``relics`` 这类顶层命名数组统一成数组（缺省为空） */
export const asArray = <T = unknown>(value: unknown): T[] =>
    Array.isArray(value) ? (value as T[]) : [];

const mockUrl = (name: string) => `${import.meta.env.BASE_URL}mock/${name}Response.json`;
/**
 * 线上与 wiki 同源（COS 绑在 wiki 域名下），所以走相对地址，
 * 和 ``editPage`` / ``getMapConfig`` 一致；跨域请求会被 Cloudflare 挑战拦下。
 * DEV 里 ``/api`` 由 ``vite.config.ts`` 的 proxy 转发。
 */
const luaUrl = (module: string) =>
    `/api.php?action=lua&module=${module}&format=json&utf8=1`;
const apiUrl = (name: ModuleName) => luaUrl(`Api/GetV2${name}`);

async function getJson<T>(url: string): Promise<T> {
    // 数据页会被原地覆盖，不能吃 HTTP 缓存，否则版本变化后仍可能拿到旧内容
    const response = await fetch(url, { cache: 'no-store' });
    if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);

    const text = await response.text();
    try {
        return JSON.parse(text) as T;
    } catch {
        // 常见于 lua 模块不存在 / 被 Cloudflare 挑战（返回 HTML）
        throw new Error(`${url}: 返回的不是 JSON（模块不存在或被拦截）`);
    }
}

/** ``{data: ...}`` / raw payload wrappers are both accepted */
const unwrap = (data: unknown): unknown => {
    if (data && typeof data === 'object' && 'data' in data) {
        return (data as { data: unknown }).data;
    }
    return data;
};

export async function fetchDataVersion(): Promise<VersionPayload | null> {
    try {
        const data = await getJson<unknown>(
            IS_DEV ? mockUrl('Version') : luaUrl('Api/GetV2Version'),
        );
        const payload = unwrap(data) as Record<string, unknown> | undefined;
        const version = Number(payload?.version ?? 0);
        if (!Number.isFinite(version) || version <= 0) return null;
        return { version };
    } catch {
        // 接口缺失 / 离线：由调用方退回 IndexedDB 缓存
        return null;
    }
}

/**
 * ``Api/GetV2Enum`` -> ``{enum, kinds}``：``enum`` 是各分组字典（含 effect_kind 结构），
 * ``kinds`` 是原 ``Api/GetV2EffectKind``（Wiki 上手工维护的效果种类名，可缺失）。
 */
export async function fetchEnums(): Promise<{ enums: unknown; kinds: EffectKindMap | null }> {
    const data = unwrap(await getJson<unknown>(IS_DEV ? mockUrl('Enum') : apiUrl('Enum')));
    const payload = (Array.isArray(data) ? { items: data } : data) as {
        enum?: unknown;
        kinds?: unknown;
        items?: unknown;
    } | null;

    const items = payload?.items;
    // 兼容旧形状：``{items: [enums]}`` / 裸字典
    const enums = payload?.enum ?? (Array.isArray(items) ? items[0] : items) ?? payload;
    const kinds = payload?.kinds;

    return {
        enums,
        kinds:
            kinds && typeof kinds === 'object' && !Array.isArray(kinds)
                ? (kinds as EffectKindMap)
                : null,
    };
}

/**
 * 拉取整类数据。线上模块一次返回全量（没有分页参数），DEV 读 mock 快照，
 * 两者形状一致：``{items, jobs?, relics?, extra?, rates?, baseStat?}``。
 */
export async function fetchModule<T = unknown>(name: ModuleName): Promise<ModulePayload<T>> {
    const data = unwrap(await getJson<unknown>(IS_DEV ? mockUrl(name) : apiUrl(name)));

    const payload = (Array.isArray(data) ? { items: data } : data) as {
        items?: unknown;
        extra?: unknown;
        rates?: unknown;
        baseStat?: unknown;
        jobs?: unknown;
        relics?: unknown;
    } | null;
    const rawItems = payload?.items;

    // 单条目页（Data:Enum.json）的 items 是整表对象，包成单元素数组方便调用方统一处理
    const items = Array.isArray(rawItems)
        ? (rawItems as T[])
        : rawItems && typeof rawItems === 'object'
          ? [rawItems as T]
          : null;

    if (!items) {
        throw new Error(`Api/GetV2${name}: unexpected payload`);
    }

    return {
        items,
        count: items.length,
        extra: payload?.extra,
        rates: payload?.rates,
        baseStat: payload?.baseStat,
        jobs: payload?.jobs,
        relics: payload?.relics,
    };
}
